"""
Общий интерфейс LLM-провайдера — то, ради чего затевался сменный слой.

Пайплайн, кэш и поиск знают про провайдера ровно одно: у него есть generate().
Поэтому смена модели не трогает остальную систему — это и есть тезис урока
«RAG не зависит от конкретной LLM», доведённый до кода.
"""
from abc import ABC, abstractmethod


class LLMProvider(ABC):
    """Базовый класс провайдера генерации.

    Атрибуты:
        name  — короткое имя для CLI и ключа кэша (ollama | gigachat | kie);
        model — конкретная модель, тоже попадает в ключ кэша;
        zone  — зона данных по 152-ФЗ: 🟢 (можно) или 🔴 (только РФ-контур).
                Хранится рядом с провайдером, чтобы вопрос «куда уходит текст»
                был виден в интерфейсе, а не только в голове у автора.
    """

    name: str = "base"
    model: str = ""
    zone: str = ""

    @abstractmethod
    def generate(self, system_prompt: str, user_prompt: str) -> str:
        """Сгенерировать ответ по системному промпту и собранному контексту."""

    def close(self) -> None:
        """Освободить ресурсы (HTTP-клиент и т.п.). По умолчанию нечего закрывать."""

    def __str__(self) -> str:
        return f"{self.name} ({self.model}) {self.zone}"
